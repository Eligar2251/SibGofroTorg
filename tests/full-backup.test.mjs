test('Postgres snapshot discovers tables and restore is atomic, preserves triggers and protects permissions', async () => {
  const db = new PGlite();
  try {
    await db.exec(`create role anon; create role authenticated; create role service_role;
      create table parent (id bigint generated by default as identity primary key, title text not null);
      create table child (id bigint generated by default as identity primary key, parent_id bigint references parent(id), note text);
      create table newly_added (key text primary key, payload jsonb);
      create function mutate_title() returns trigger language plpgsql as $$begin new.title := 'MUTATED'; return new; end$$;
      create trigger trg_title before update on parent for each row execute function mutate_title();
      create function prevent_truncate() returns trigger language plpgsql as $$begin raise exception 'truncate trigger fired'; end$$;
      create trigger trg_truncate before truncate on parent for each statement execute function prevent_truncate();
      create trigger trg_replica before update on parent for each row execute function mutate_title();
      alter table parent enable replica trigger trg_replica;
      insert into parent (title) values ('original'); insert into child (parent_id,note) values (1,'child');
      insert into newly_added values ('key', '{"nested":true}');`);
    await db.exec(fs.readFileSync('supabase/migration_complete_app_backup.sql', 'utf8'));
    const snapshot = (await db.query('select public.sgt_export_app_data() as v')).rows[0].v;
    assert.deepEqual(Object.keys(snapshot.tables).sort(), ['child', 'newly_added', 'parent']);
    assert.equal(snapshot.totalRows, 3);
    assert.equal(validateFullSnapshot(snapshot).tables.parent[0].title, 'original');
    await db.exec("delete from child; delete from parent; insert into parent(title) values('other'); delete from newly_added;");
    await db.query('select public.sgt_restore_app_data($1::jsonb)', [JSON.stringify(snapshot)]);
    assert.equal((await db.query('select title from parent')).rows[0].title, 'original');
    assert.equal((await db.query('select note from child')).rows[0].note, 'child');
    assert.equal((await db.query("select tgenabled from pg_trigger where tgname='trg_title'")).rows[0].tgenabled, 'O');
    assert.equal((await db.query("select tgenabled from pg_trigger where tgname='trg_replica'")).rows[0].tgenabled, 'R');
    assert.ok((await db.query("insert into parent (title) values ('next') returning id")).rows[0].id > 1);
    await db.exec("update parent set title='changed' where id=1");
    assert.equal((await db.query('select title from parent where id=1')).rows[0].title, 'MUTATED');
    const before = (await db.query('select id,title from parent order by id')).rows;
    const broken = structuredClone(snapshot); broken.tables.parent[0].title = null;
    await assert.rejects(db.query('select public.sgt_restore_app_data($1::jsonb)', [JSON.stringify(broken)]));
    assert.deepEqual((await db.query('select id,title from parent order by id')).rows, before);
    assert.equal((await db.query("select tgenabled from pg_trigger where tgname='trg_title'")).rows[0].tgenabled, 'O');
    const malformed = structuredClone(snapshot); malformed.tables.parent = [123];
    await assert.rejects(db.query('select public.sgt_restore_app_data($1::jsonb)', [JSON.stringify(malformed)]));
    assert.deepEqual((await db.query('select id,title from parent order by id')).rows, before);
    await db.exec('create table new_target_only(id int primary key)');
    await assert.rejects(db.query('select public.sgt_restore_app_data($1::jsonb)', [JSON.stringify(snapshot)]), /table lists differ/i);
    assert.deepEqual((await db.query('select id,title from parent order by id')).rows, before);
    await db.exec('set role anon');
    await assert.rejects(db.query('select public.sgt_export_app_data()'), /permission denied/i);
    await db.exec('reset role; set role service_role');
    assert.ok((await db.query('select public.sgt_export_app_data() as v')).rows[0].v);
    await db.exec('reset role');
  } finally { await db.close(); }
});

test('server local snapshot and restore are disabled while old data is retained', async () => {
  assert.equal(readFullBackupSettings().enabled, false);
  saveDbRuntimeConfig({ activeBackend: 'local', autoBackupEnabled: false });
  const snapshot = { app:'SibGofroTorg', backupFormat:'sgt-public-v1', version:1, exportedAt:'2026-01-01T00:00:00Z', totalRows:1,
    tables:{ products:[{id:'p1',name:'box'}] },
    columns:{ products:[{name:'id',type:'text',generated:'',identity:''},{name:'name',type:'text',generated:'',identity:''}] },
    sequences:{products:{}} };
  importLocalDbSnapshot(snapshot, 'replace');
  const local = getLocalJsonDbClient();
  await local.from('products').update({name:'old data'}).eq('id','p1');
  const prior = fs.readFileSync(path.join(temp, 'local-db.json'), 'utf8');
  await assert.rejects(captureFullSnapshot('local'), /отключена/);
  await assert.rejects(restoreFullSnapshot(snapshot, 'local', true), /отключено/);
  saveFullBackupSettings({ enabled:true, intervalSec:150, targets:{local:true,primary:false,secondary:false} });
  assert.equal(readFullBackupSettings().targets.local, false);
  await assert.rejects(runFullReplication(), /Серверная JSON-БД не используется/);
  assert.equal(fs.readFileSync(path.join(temp, 'local-db.json'), 'utf8'), prior);
  assert.ok(getLocalDbSummary().pendingMutationsCount > 0);
  const bad = structuredClone(snapshot); delete bad.tables.products[0].name;
  assert.throws(() => validateFullSnapshot(bad), /неполные строки/);
});

test('snapshot replication copies inserts and deletions and protects concurrently modified local data', async () => {
  const primary = new PGlite(); const secondary = new PGlite(); const originalFetch = globalThis.fetch;
  const sql = fs.readFileSync('supabase/migration_complete_app_backup.sql', 'utf8');
  const setup = `create role anon; create role authenticated; create role service_role;
    create table products(id text primary key, name text, updated_at timestamptz default now());
    create table rent_orgs(id text primary key);
    create table doc_counters(key text primary key, value int);`;
  const envNames = ['SUPABASE_URL', 'SUPABASE_SERVICE_ROLE_KEY', 'SUPABASE_SECONDARY_URL', 'SUPABASE_SECONDARY_SECRET_KEY'];
  const previous = envNames.map(k => process.env[k]);
  try {
    await primary.exec(setup); await secondary.exec(setup);
    await primary.exec(sql); await secondary.exec(sql);
    await primary.exec("insert into products(id,name) values ('remote-1','First'), ('remote-2','Second')");
    process.env.SUPABASE_URL = 'https://primary.test'; process.env.SUPABASE_SERVICE_ROLE_KEY = 'fake-primary-secret';
    process.env.SUPABASE_SECONDARY_URL = 'https://secondary.test'; process.env.SUPABASE_SECONDARY_SECRET_KEY = 'fake-secondary-secret';
    let concurrent = false;
    globalThis.fetch = async (input, init) => {
      const url = String(input); const db = url.includes('primary.test') ? primary : secondary;
      try {
        if (url.includes('/rpc/sgt_export_app_data')) {
          const snapshot = (await db.query('select public.sgt_export_app_data() as v')).rows[0].v;
          if (concurrent) await getLocalJsonDbClient().from('products').update({name:'offline change'}).eq('id','remote-1');
          return new Response(JSON.stringify(snapshot), { status:200, headers:{'Content-Type':'application/json'} });
        }
        if (url.includes('/rpc/sgt_restore_app_data')) {
          const parsed = JSON.parse(String(init.body));
          const result = (await db.query('select public.sgt_restore_app_data($1::jsonb) as v',[JSON.stringify(parsed.p_snapshot)])).rows[0].v;
          return new Response(JSON.stringify(result), { status:200, headers:{'Content-Type':'application/json'} });
        }
        throw new Error(`Unexpected URL ${url}`);
      } catch (e) { return new Response(JSON.stringify({ message:e.message, code:'TEST' }), { status:400, headers:{'Content-Type':'application/json'} }); }
    };
    // Reset the old local pending queue explicitly for an isolated replication test.
    const initial = (await primary.query('select public.sgt_export_app_data() as v')).rows[0].v;
    importLocalDbSnapshot(initial, 'replace');
    saveDbRuntimeConfig({ activeBackend:'primary', autoFailover:true });
    saveFullBackupSettings({ enabled:true, intervalSec:150, targets:{ local:true, primary:false, secondary:true } });
    let status = await runFullReplication();
    assert.equal(status.targets.local.state, 'paused');
    assert.equal(status.targets.secondary.state, 'ok');
    assert.deepEqual((await secondary.query('select id from products order by id')).rows.map(r=>r.id), ['remote-1','remote-2']);
    await primary.exec("delete from products where id='remote-2'; update products set name='Changed' where id='remote-1'");
    status = await runFullReplication();
    assert.equal(status.targets.secondary.state, 'ok');
    assert.deepEqual((await secondary.query('select id,name from products')).rows, [{ id:'remote-1', name:'Changed' }]);
    assert.equal((await getLocalJsonDbClient().from('products').select('*')).data.length, 2);
    concurrent = true;
    status = await runFullReplication();
    assert.equal(status.targets.local.state, 'paused');
    assert.equal((await getLocalJsonDbClient().from('products').select('*').eq('id','remote-1').single()).data.name, 'offline change');
    assert.ok(getLocalDbSummary().pendingMutationsCount > 0);
  } finally {
    globalThis.fetch = originalFetch;
    envNames.forEach((key, i) => previous[i] === undefined ? delete process.env[key] : process.env[key] = previous[i]);
    saveFullBackupSettings({ enabled:false, intervalSec:150, targets:{local:false,primary:false,secondary:false} });
    await primary.close(); await secondary.close();
  }
});
