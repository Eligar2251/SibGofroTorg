/* =========================================================
   FILE: public/sw.js
   Service worker сайта (подключается /sw.js на всех публичных
   страницах; админка использует свой /admin-sw.js).

   ЗАЧЕМ ОН НУЖЕН, ЕСЛИ НИЧЕГО НЕ КЕШИРУЕТ
   Без зарегистрированного service worker браузер не предлагает
   «Установить приложение» / «Добавить на главный экран» в режиме
   standalone, то есть сайт открывается в обычной вкладке с адресной
   строкой. Пустой worker — минимальная цена за безрамочный режим.

   ЧЕГО ЗДЕСЬ НЕТ СОЗНАТЕЛЬНО
   Кеша нет: any-кеш на Next.js (ISR, RSC-пейлоады, API-роуты)
   быстро устаревает и ломает обновления. Страницы всегда идут в
   сеть, кеш ассетов отдаёт сам Next (immutable-заголовки). Пустой
   обработчик fetch ниже ничего не перехватывает — он нужен только
   для критерия устанавливаемости в старых Chrome (см. комментарий).
   ========================================================= */

const VERSION = "sibgofrotorg-sw-1";

self.addEventListener("install", (event) => {
  // Не ждём закрытия старых вкладок — новая версия включается сразу.
  event.waitUntil(self.skipWaiting());
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    (async () => {
      // Чистим чужие кеши, если они когда-либо появятся.
      const keys = await caches.keys();
      await Promise.all(
        keys.filter((key) => key !== VERSION).map((key) => caches.delete(key))
      );
      await self.clients.claim();
    })()
  );
});

/* Пустой обработчик fetch: мы НЕ вызываем respondWith, поэтому все
   запросы идут в сеть как обычно (кеш не подключён). Он нужен только
   чтобы старые Chrome (до ~126) считали PWA «устанавливаемым» —
   тогда пункт «Установить приложение» / «Добавить на главный экран»
   появляется у всех, а не только на новых версиях браузера. */
self.addEventListener("fetch", () => {
  /* no-op: осознанно ничего не перехватываем */
});
