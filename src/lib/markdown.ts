/**
 * Грубая очистка markdown-разметки для мета-описаний/JSON-LD,
 * где нужен чистый текст без символов форматирования.
 */
export function stripMarkdown(text: string): string {
  return text
    .replace(/!\[[^\]]*\]\([^)]*\)/g, " ") // картинки
    .replace(/\[([^\]]*)\]\([^)]*\)/g, "$1") // ссылки → текст
    .replace(/^#{1,6}\s+/gm, "") // заголовки
    .replace(/^>\s?/gm, "") // цитаты
    .replace(/^(\s*[-*+]\s+|\s*\d+\.\s+)/gm, "") // маркеры списков
    .replace(/(\*\*|__)(.*?)\1/g, "$2") // жирный
    .replace(/(\*|_)(.*?)\1/g, "$2") // курсив
    .replace(/~~(.*?)~~/g, "$1") // зачёркивание
    .replace(/`{1,3}([^`]*)`{1,3}/g, "$1") // код
    .replace(/^\s*[-|:\s]+\|?\s*$/gm, "") // разделители таблиц GFM
    .replace(/\|/g, " ") // ячейки таблиц
    .replace(/\s+/g, " ")
    .trim();
}
