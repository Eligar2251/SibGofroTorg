/* Объём коробки в литрах по габаритам (мм) */
function volumeLiters(p: {
  dimensionLength?: number | null;
  dimensionWidth?: number | null;
  dimensionHeight?: number | null;
}): number {
  const { dimensionLength: l, dimensionWidth: w, dimensionHeight: h } = p;
  if (!l || !w || !h) return 0;
  return (l * w * h) / 1000 / 1000;
}

